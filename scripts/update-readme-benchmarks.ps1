<#
.SYNOPSIS
  Regenerates the benchmark comparison table inside README.md.

.DESCRIPTION
  Runs `cargo run -p xtask -- compare --json` (release binary, Varn vs Bun vs Node),
  renders a Markdown table and replaces the block between the markers
  <!-- BENCHMARKS:START --> and <!-- BENCHMARKS:END --> in README.md.
  Called by scripts/verify.ps1 (full run); can also be run by hand.

.PARAMETER Runs
  Repetitions per benchmark per runtime (default 7, two are warmup).

.PARAMETER Only
  Restrict to the named benchmarks (for quick manual refreshes).

.PARAMETER Readme
  README to update (default: README.md at the repository root).
#>
[CmdletBinding()]
param(
    [int]$Runs = 7,
    [string[]]$Only,
    [string]$Readme
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
if (-not $Readme) { $Readme = Join-Path $root 'README.md' }

$startMarker = '<!-- BENCHMARKS:START -->'
$endMarker = '<!-- BENCHMARKS:END -->'

$text = [System.IO.File]::ReadAllText($Readme)
$startIdx = $text.IndexOf($startMarker)
$endIdx = $text.IndexOf($endMarker)
if ($startIdx -lt 0 -or $endIdx -lt $startIdx) {
    throw "README.md no contiene los marcadores $startMarker / $endMarker."
}

$cargoArgs = @('run', '--quiet', '--package', 'xtask', '--', 'compare', '--json', '--skip-python', '--runs', $Runs.ToString())
if ($Only) { $cargoArgs += @('--only', (($Only | ForEach-Object { $_ -split ',' }) -join ',')) }

Push-Location $root
try {
    $raw = & cargo @cargoArgs 2>$null
    if ($LASTEXITCODE -ne 0) { throw "xtask compare fallo (codigo $LASTEXITCODE). Compila antes con: cargo build --release --bin vn" }
    $commit = (& git rev-parse --short HEAD 2>$null)
}
finally {
    Pop-Location
}

$data = ($raw -join "`n") | ConvertFrom-Json
$runtimes = @($data.runtimes)

function Get-Median($stats, $name) {
    $entry = $stats.PSObject.Properties[$name]
    if ($null -eq $entry -or $null -eq $entry.Value -or $entry.Value.count -eq 0) { return $null }
    return [double]$entry.Value.median
}

function Format-Ms($value) {
    if ($null -eq $value) { return '—' }
    return ('{0:N1}' -f $value).Replace(',', '')
}

$rows = New-Object System.Collections.Generic.List[string]
$comparable = 0
$fastest = 0
foreach ($bench in ($data.benchmarks | Sort-Object name)) {
    $vn = Get-Median $bench.stats 'vn'
    $bun = Get-Median $bench.stats 'bun'
    $node = Get-Median $bench.stats 'node'
    $verdict = [string]$bench.verdict
    $isComparable = $bench.output_ok -and $null -ne $bench.work_ratio
    if ($isComparable) {
        $comparable++
        if ($verdict -match 'faster') { $fastest++ }
    }
    if (-not $bench.output_ok) {
        $vn = $null; $bun = $null; $node = $null
        $result = 'output mismatch'
    } elseif ($null -eq $bench.work_ratio) {
        $result = '—'
    } elseif ($verdict -eq 'not resolved') {
        $result = 'tie (within noise)'
    } else {
        $result = $verdict
    }
    $rows.Add(('| `{0}` | {1} | {2} | {3} | {4} |' -f $bench.name, (Format-Ms $vn), (Format-Ms $bun), (Format-Ms $node), $result))
}

$date = (Get-Date).ToString('yyyy-MM-dd')
$os = [System.Runtime.InteropServices.RuntimeInformation]::OSDescription
$summary = "Varn is the fastest runtime in **$fastest of $comparable** comparable workloads (steady state, work time without process startup)."

$block = @(
    $startMarker
    "_Generated by ``scripts/verify.ps1`` on $date from commit ``$commit`` — $($data.cpu), $os. Median of $($data.runs) runs ($($data.warmup) warmup), release build, single machine._"
    ''
    $summary
    ''
    '| Benchmark | Varn (ms) | Bun (ms) | Node (ms) | Varn vs. best rival |'
    '|---|--:|--:|--:|---|'
) + $rows + @(
    ''
    'Times are whole-process medians. A row only counts when every runtime prints the same checksum; rows that do not are listed as `output mismatch` and carry no timings. A tie means the steady-state difference is under 5% or inside the run-to-run range. Methodology and caveats: [`tests/benchmarks/README.md`](tests/benchmarks/README.md).'
    $endMarker
)

$newline = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
$replacement = ($block -join $newline)
$updated = $text.Substring(0, $startIdx) + $replacement + $text.Substring($endIdx + $endMarker.Length)
[System.IO.File]::WriteAllText($Readme, $updated, (New-Object System.Text.UTF8Encoding($false)))

Write-Host "README.md actualizado: $fastest/$comparable cargas comparables mas rapidas en Varn ($($rows.Count) filas)."
