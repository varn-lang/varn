impl TokenKind {
    pub fn from_u32(v: u32) -> Self {
        if v <= TokenKind::Out as u32 {
            unsafe { std::mem::transmute::<u32, TokenKind>(v) }
        } else {
            TokenKind::Dynamic
        }
    }
}
